// 文字列型　（string type)の変数nameの宣言と初期化
let name: string = "TypeScriptの勉強";
// 数値型（number type）の変数priorityの宣言と初期化
let priority: number = 5;
// Data型の変数 deadline の宣言と初期化
// 2025年10月21日 14:15 で初期化したつもり
let deadline: Date = new Date(2025, 10, 21, 14, 15);
console.log(name,priority,deadline) // console.log　は可変長引数を受け取り可能
